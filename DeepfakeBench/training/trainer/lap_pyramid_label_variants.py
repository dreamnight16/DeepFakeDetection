"""
Laplacian Pyramid Mixup — 2×3 Factorial Ablation (label × scope)
================================================================
Six variants generated by crossing two factors:

  Factor A — hard_label:
      0 : RF soft label forced to 0 (real)
      1 : RF soft label forced to 1 (fake)
  Factor B — mix_scope:
      'top'    : mix only coarsest Gaussian level G_K; Laplacian from real
      'bottom' : mix only finest Laplacian level L_0; G_K & higher from real
      'full'   : mix ALL Laplacian levels L_0..L_{K-1}; G_K from real

2×3 combinations:
  ┌──────────┬───────────────────┬───────────────────┬───────────────────┐
  │          │  mix_scope = top  │ mix_scope = bottom│ mix_scope = full  │
  ├──────────┼───────────────────┼───────────────────┼───────────────────┤
  │ label=0  │  (1) G_K, ỹ=0     │  (2) L_0, ỹ=0     │  (5) all L, ỹ=0   │
  │ label=1  │  (3) G_K, ỹ=1     │  (4) L_0, ỹ=1     │  (6) all L, ỹ=1   │
  └──────────┴───────────────────┴───────────────────┴───────────────────┘

mixup_mode values:
    lap_pyramid_label0_top     — label=0, scope=top    (G_K, labeled real)
    lap_pyramid_label0_bottom  — label=0, scope=bottom  (L_0, labeled real)
    lap_pyramid_label1_top     — label=1, scope=top    (G_K, labeled fake)
    lap_pyramid_label1_bottom  — label=1, scope=bottom  (L_0, labeled fake)
    lap_pyramid_label0_full    — label=0, scope=full    (all Laplacian, labeled real)
    lap_pyramid_label1_full    — label=1, scope=full    (all Laplacian, labeled fake)

Author: personal experiment
"""

import numpy as np
import torch

# Reuse pyramid helpers from trainer_v2 (module-level, no circular import)
from trainer.trainer_v2 import (
    build_gaussian_pyramid,
    build_laplacian_pyramid,
    reconstruct_from_lap,
)


def lap_pyramid_label_mixup(x, y, alpha=1.0, gamma=5.0, num_levels=3,
                             epsilon=1e-8, hard_label=1, mix_scope='bottom',
                             beta_b=None, beta_flip=False):
    """2×3 factorial Laplacian pyramid mixup.

    Parameters
    ----------
    hard_label : int (0 or 1)
        Forced soft label for RF pyramid-mixed samples.
    mix_scope : str
        'top'    — mix only coarsest Gaussian level G_K; Laplacian from real
        'bottom' — mix only finest Laplacian level L_0; G_K & higher from real
        'full'   — mix ALL Laplacian levels L_0..L_{K-1}; G_K from real
    beta_b : float or None
        Second Beta parameter b.  When None (default), uses symmetric
        Beta(alpha, alpha).  When set, uses asymmetric Beta(alpha, beta_b),
        e.g. Beta(2, 5) — left-heavy, λ ~ 0.286 on average.
    beta_flip : bool
        When True, λ = 1 − Beta(alpha, beta_b).  Useful for inverting the
        asymmetry direction — e.g. with Beta(2,5), flip gives λ ~ 0.714.

    Returns
    -------
    mixed_x : Tensor [n, C, H, W]
    mixed_y : Tensor [n]  — soft label
    mixed_label : Tensor [n]  — hard label (anchor class)
    """
    b = beta_b if beta_b is not None else alpha
    lam = np.random.beta(alpha, b) if alpha > 0 else 1.0
    if beta_flip:
        lam = 1.0 - lam
    lam_t = torch.tensor(lam, dtype=torch.float32, device=x.device)

    index = torch.randperm(x.size(0), device=x.device)
    y_a = y.float()
    y_b = y[index].float()

    rr_mask = (y_a == 0) & (y_b == 0)
    ff_mask = (y_a == 1) & (y_b == 1)
    rf_mask = (y_a == 0) & (y_b == 1)
    fr_mask = (y_a == 1) & (y_b == 0)

    # ── RR: pixel-space, label = 0 ──────────────────────────────────────────
    rr_n = rr_mask.sum().item()
    if rr_n > 0:
        rr_x = lam_t * x[rr_mask] + (1.0 - lam_t) * x[index[rr_mask]]
        rr_y = torch.zeros(rr_n, device=x.device)
        rr_label = torch.zeros(rr_n, dtype=y.dtype, device=x.device)
    else:
        rr_x = torch.empty(0, *x.shape[1:], device=x.device)
        rr_y = torch.empty(0, device=x.device)
        rr_label = torch.empty(0, dtype=y.dtype, device=x.device)

    # ── FF: pixel-space, label = 1 ──────────────────────────────────────────
    ff_n = ff_mask.sum().item()
    if ff_n > 0:
        ff_x = lam_t * x[ff_mask] + (1.0 - lam_t) * x[index[ff_mask]]
        ff_y = torch.ones(ff_n, device=x.device)
        ff_label = torch.ones(ff_n, dtype=y.dtype, device=x.device)
    else:
        ff_x = torch.empty(0, *x.shape[1:], device=x.device)
        ff_y = torch.empty(0, device=x.device)
        ff_label = torch.empty(0, dtype=y.dtype, device=x.device)

    # ── RF: cross-class pairs — pyramid mixup ─────────────────────────────
    rf_idx = rf_mask.nonzero(as_tuple=True)[0]
    fr_idx = fr_mask.nonzero(as_tuple=True)[0]
    real_pos = torch.cat([rf_idx, index[fr_idx]])
    fake_pos = torch.cat([index[rf_idx], fr_idx])
    n_rf = len(real_pos)

    if n_rf > 0:
        x_r = x[real_pos]
        x_f = x[fake_pos]

        gpyr_r = build_gaussian_pyramid(x_r, num_levels)
        gpyr_f = build_gaussian_pyramid(x_f, num_levels)
        G_K_r = gpyr_r[-1]
        G_K_f = gpyr_f[-1]
        lap_r = build_laplacian_pyramid(gpyr_r)
        lap_f = build_laplacian_pyramid(gpyr_f)

        q_val = 1.0 - lam

        # ── Mix scope: which level gets fake injection ──────────────────
        if mix_scope == 'top':
            # Only coarsest Gaussian G_K mixed; all Laplacian from real
            G_K = (1.0 - q_val) * G_K_r + q_val * G_K_f
            lap_mixed = [lap_r[k] for k in range(num_levels)]
        elif mix_scope == 'bottom':
            # Only finest Laplacian L_0 mixed; G_K and higher Laplacian from real
            G_K = G_K_r
            L_0_mixed = (1.0 - q_val) * lap_r[0] + q_val * lap_f[0]
            lap_mixed = [L_0_mixed] + [lap_r[k] for k in range(1, num_levels)]
        elif mix_scope == 'full':
            # All Laplacian levels mixed; G_K from real (general pyramid mixing)
            G_K = G_K_r
            lap_mixed = [(1.0 - q_val) * lap_r[k] + q_val * lap_f[k]
                         for k in range(num_levels)]
        else:
            raise ValueError(f"Unknown mix_scope: {mix_scope}")

        # ── Label: forced to 0 or 1 ─────────────────────────────────────
        rf_y = torch.full((n_rf,), float(hard_label), device=x.device)

        rf_x = reconstruct_from_lap(G_K, lap_mixed)
        rf_x = torch.clamp(rf_x,
                           x_r.amin(dim=(-3, -2, -1), keepdim=True),
                           x_r.amax(dim=(-3, -2, -1), keepdim=True))
        # Hard label follows the soft label
        rf_label = torch.full((n_rf,), hard_label, dtype=y.dtype, device=x.device)
    else:
        rf_x = torch.empty(0, *x.shape[1:], device=x.device)
        rf_y = torch.empty(0, device=x.device)
        rf_label = torch.empty(0, dtype=y.dtype, device=x.device)

    # ── Combine ───────────────────────────────────────────────────────────
    parts_x = [t for t in [rr_x, ff_x, rf_x] if t.numel() > 0]
    parts_y = [t for t in [rr_y, ff_y, rf_y] if t.numel() > 0]
    parts_label = [t for t in [rr_label, ff_label, rf_label] if t.numel() > 0]

    mixed_x = torch.cat(parts_x, dim=0)
    mixed_y = torch.cat(parts_y, dim=0)
    mixed_label = torch.cat(parts_label, dim=0)

    # ── loss_mask ──────────────────────────────────────────────────────────
    mask_parts = []
    if rr_n > 0:
        mask_parts.append(torch.ones(rr_n, device=x.device, dtype=torch.float32))
    if ff_n > 0:
        mask_parts.append(torch.ones(ff_n, device=x.device, dtype=torch.float32))
    if n_rf > 0:
        mask_parts.append(torch.ones(n_rf, device=x.device, dtype=torch.float32))
    loss_mask = torch.cat(mask_parts, dim=0) if mask_parts else mixed_y.new_zeros(0)

    return mixed_x, mixed_y, mixed_label, loss_mask
